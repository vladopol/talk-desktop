import type * as Koffi from 'koffi'
import type { ControlledSource, HitResult, Injector, KeyTargetResult, LeaveElevatedResult, ModifierState, MouseButton, OsPoint, OsRect, WindowStateResult } from './injector.types.ts'
import type { NativeKey } from './keymap.ts'

import { clipboard, screen, systemPreferences } from 'electron'

// See REMOTE-CONTROL.md, "Injecting input into the OS" - "macOS"
const kCGEventSourceStatePrivate = -1
const kCGEventSourceStateHIDSystemState = 1
const kCGHIDEventTap = 0
const kCGEventLeftMouseDown = 1
const kCGEventLeftMouseUp = 2
const kCGEventRightMouseDown = 3
const kCGEventRightMouseUp = 4
const kCGEventMouseMoved = 5
const kCGEventLeftMouseDragged = 6
const kCGEventRightMouseDragged = 7
const kCGEventOtherMouseDown = 25
const kCGEventOtherMouseUp = 26
const kCGEventOtherMouseDragged = 27
const kCGMouseEventClickState = 1
const kCGScrollEventUnitPixel = 0
const kCGWindowListOptionOnScreenOnly = 1
const kCGWindowListOptionIncludingWindow = 8
const kCGWindowListExcludeDesktopElements = 16
const kCFStringEncodingUTF8 = 0x08000100
const kCFNumberSInt64Type = 4
const kCFNumberFloat64Type = 6

const FLAG_SHIFT = 0x20000
const FLAG_CONTROL = 0x40000
const FLAG_ALTERNATE = 0x80000
const FLAG_COMMAND = 0x100000

/** kVK_* of modifier keys → the event flag they set */
const MODIFIER_FLAGS: Record<number, number> = {
	0x38: FLAG_SHIFT,
	0x3c: FLAG_SHIFT,
	0x3b: FLAG_CONTROL,
	0x3e: FLAG_CONTROL,
	0x3a: FLAG_ALTERNATE,
	0x3d: FLAG_ALTERNATE,
	0x37: FLAG_COMMAND,
	0x36: FLAG_COMMAND,
}

/** Pasteboard types password managers put next to a secret (nspasteboard.org) */
const SENSITIVE_PASTEBOARD_TYPES = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType']

/** kCGCursorWindowLevel and above: the mouse cursor itself, never a click target */
const CURSOR_WINDOW_LAYER = 2147483630

/** Windows thinner than this are the click-through strips of the screensharing indicator */
const INDICATOR_STRIP_MAX = 8

/** Pixels per 1/120 of a wheel notch */
const WHEEL_PIXELS_PER_UNIT = 100 / 120

type Pointer = unknown

type Bindings = {
	koffi: typeof Koffi
	source: Pointer
	keys: Record<'number' | 'pid' | 'layer' | 'bounds' | 'onscreen' | 'alpha', Pointer>
	CFRelease: (ref: Pointer) => void
	CFArrayGetCount: (array: Pointer) => number
	CFArrayGetValueAtIndex: (array: Pointer, index: number) => Pointer
	CFDictionaryGetValue: (dict: Pointer, key: Pointer) => Pointer
	CFNumberGetValue: (number: Pointer, type: number, value: BigInt64Array | Float64Array) => boolean
	CFBooleanGetValue: (bool: Pointer) => boolean
	CGRectMakeWithDictionaryRepresentation: (dict: Pointer, rect: Record<string, unknown>) => boolean
	CGWindowListCopyWindowInfo: (option: number, windowId: number) => Pointer
	CGEventCreate: (source: Pointer) => Pointer
	CGEventGetLocation: (event: Pointer) => OsPoint
	CGEventCreateMouseEvent: (source: Pointer, type: number, point: OsPoint, button: number) => Pointer
	CGEventCreateScrollWheelEvent2: (source: Pointer, units: number, count: number, wheel1: number, wheel2: number, wheel3: number) => Pointer
	CGEventCreateKeyboardEvent: (source: Pointer, key: number, down: boolean) => Pointer
	CGEventSetIntegerValueField: (event: Pointer, field: number, value: number) => void
	CGEventSetFlags: (event: Pointer, flags: number) => void
	CGEventPost: (tap: number, event: Pointer) => void
	CGPreflightPostEventAccess: () => boolean
	CGRequestPostEventAccess: () => boolean
	CGEventSourceFlagsState: (state: number) => number | bigint
}

type WindowInfo = { id: number, pid: number, layer: number, bounds: OsRect, onscreen: boolean, alpha: number }

let bindings: Bindings | null = null
let bindingsFailed = false

/**
 * Lazily bind CoreGraphics and CoreFoundation
 */
function getBindings(): Bindings | null {
	if (bindings || bindingsFailed) {
		return bindings
	}
	try {
		// eslint-disable-next-line @typescript-eslint/no-require-imports -- koffi is a native module kept external from the bundle
		const koffi = require('koffi') as typeof Koffi
		const cg = koffi.load('/System/Library/Frameworks/ApplicationServices.framework/ApplicationServices')
		const cf = koffi.load('/System/Library/Frameworks/CoreFoundation.framework/CoreFoundation')

		koffi.struct('RC_CGPoint', { x: 'double', y: 'double' })
		koffi.struct('RC_CGSize', { width: 'double', height: 'double' })
		koffi.struct('RC_CGRect', { origin: 'RC_CGPoint', size: 'RC_CGSize' })

		const CFStringCreateWithCString = cf.func('void *CFStringCreateWithCString(void *alloc, const char *str, uint32_t encoding)')
		const CGEventSourceCreate = cg.func('void *CGEventSourceCreate(int32_t state)')
		const CGEventSourceSetLocalEventsSuppressionInterval = cg.func('void CGEventSourceSetLocalEventsSuppressionInterval(void *source, double seconds)')

		const key = (name: string) => CFStringCreateWithCString(null, name, kCFStringEncodingUTF8)

		// A private source, and no suppression of local events after a synthetic one: by
		// default macOS ignores the hardware mouse for 0.25 s after every injected event, and
		// the presenter could never take the mouse back
		const source = CGEventSourceCreate(kCGEventSourceStatePrivate)
		CGEventSourceSetLocalEventsSuppressionInterval(source, 0)

		bindings = {
			koffi,
			source,
			keys: {
				number: key('kCGWindowNumber'),
				pid: key('kCGWindowOwnerPID'),
				layer: key('kCGWindowLayer'),
				bounds: key('kCGWindowBounds'),
				onscreen: key('kCGWindowIsOnscreen'),
				alpha: key('kCGWindowAlpha'),
			},
			CFRelease: cf.func('void CFRelease(void *ref)'),
			CFArrayGetCount: cf.func('long CFArrayGetCount(void *array)'),
			CFArrayGetValueAtIndex: cf.func('void *CFArrayGetValueAtIndex(void *array, long index)'),
			CFDictionaryGetValue: cf.func('void *CFDictionaryGetValue(void *dict, void *key)'),
			CFNumberGetValue: cf.func('bool CFNumberGetValue(void *number, long type, void *value)'),
			CFBooleanGetValue: cf.func('bool CFBooleanGetValue(void *bool)'),
			CGRectMakeWithDictionaryRepresentation: cg.func('bool CGRectMakeWithDictionaryRepresentation(void *dict, _Out_ RC_CGRect *rect)'),
			CGWindowListCopyWindowInfo: cg.func('void *CGWindowListCopyWindowInfo(uint32_t option, uint32_t windowId)'),
			CGEventCreate: cg.func('void *CGEventCreate(void *source)'),
			CGEventGetLocation: cg.func('RC_CGPoint CGEventGetLocation(void *event)'),
			CGEventCreateMouseEvent: cg.func('void *CGEventCreateMouseEvent(void *source, uint32_t type, RC_CGPoint point, uint32_t button)'),
			CGEventCreateScrollWheelEvent2: cg.func('void *CGEventCreateScrollWheelEvent2(void *source, uint32_t units, uint32_t count, int32_t wheel1, int32_t wheel2, int32_t wheel3)'),
			CGEventCreateKeyboardEvent: cg.func('void *CGEventCreateKeyboardEvent(void *source, uint16_t key, bool down)'),
			CGEventSetIntegerValueField: cg.func('void CGEventSetIntegerValueField(void *event, uint32_t field, int64_t value)'),
			CGEventSetFlags: cg.func('void CGEventSetFlags(void *event, uint64_t flags)'),
			CGEventPost: cg.func('void CGEventPost(uint32_t tap, void *event)'),
			CGPreflightPostEventAccess: cg.func('bool CGPreflightPostEventAccess()'),
			CGRequestPostEventAccess: cg.func('bool CGRequestPostEventAccess()'),
			CGEventSourceFlagsState: cg.func('uint64_t CGEventSourceFlagsState(int32_t state)'),
		}
	} catch (error) {
		console.error('[remote-control] Failed to load the macOS input bindings:', error)
		bindingsFailed = true
	}
	return bindings
}

/**
 * Injects input with CGEvent
 */
export class MacInjector implements Injector {
	readonly os = 'mac' as const

	private pressedKeys = new Set<number>()
	private pressedButtons = new Set<MouseButton>()
	private lastPoint: OsPoint = { x: 0, y: 0 }

	availability() {
		const native = getBindings()
		if (!native) {
			return { ok: false as const, why: 'bindings' as const }
		}
		const trusted = native.CGPreflightPostEventAccess() || systemPreferences.isTrustedAccessibilityClient(false)
		return trusted ? { ok: true as const } : { ok: false as const, why: 'permission' as const }
	}

	requestPermission() {
		const native = getBindings()
		if (native && !native.CGRequestPostEventAccess()) {
			systemPreferences.isTrustedAccessibilityClient(true)
		}
	}

	sourceRect(source: ControlledSource): OsRect | null {
		switch (source.kind) {
			case 'screen': {
				// The global display space of CoreGraphics is Electron's DIP space on macOS
				const display = screen.getAllDisplays().find((display) => String(display.id) === source.displayId)
				return display ? { ...display.bounds } : null
			}
			case 'window':
				return source.windowId ? this.windowInfo(source.windowId)?.bounds ?? null : null
			default:
				// The full-desktop capture is not offered on macOS
				return null
		}
	}

	isOnScreen(point: OsPoint) {
		return screen.getAllDisplays().some(({ bounds }) => contains(bounds, point))
	}

	hitTest(point: OsPoint, source: ControlledSource): HitResult {
		const shared = source.kind === 'window' ? this.windowInfo(source.windowId!) : null
		for (const window of this.onScreenWindows()) {
			if (window.alpha === 0 || window.layer >= CURSOR_WINDOW_LAYER || !contains(window.bounds, point)) {
				continue
			}
			if (window.pid === process.pid) {
				if (Math.min(window.bounds.width, window.bounds.height) <= INDICATOR_STRIP_MAX) {
					continue
				}
				return 'own-window'
			}
			if (!shared) {
				return 'ok'
			}
			if (window.id === shared.id) {
				return 'ok'
			}
			// Menus and popovers of the same application, or its sheet over the window
			if (window.pid === shared.pid && (window.layer > 0 || containsRect(shared.bounds, window.bounds))) {
				return 'ok'
			}
			// The menu bar and the Dock stay controllable in window mode only when
			// they are in the frame, which they are not
			return 'window-occluded'
		}
		// No window under the point: the desktop picture and its icons, which the window list
		// leaves out (kCGWindowListExcludeDesktopElements). Fine for a screen share; a point
		// outside every screen never gets here (isOnScreen).
		if (shared) {
			return 'window-occluded'
		}
		return this.isOnScreen(point) ? 'ok' : 'outside'
	}

	keyTarget(source: ControlledSource): KeyTargetResult {
		const front = this.onScreenWindows().find((window) => window.layer === 0 && window.alpha > 0)
		if (!front) {
			return 'focus-elsewhere'
		}
		if (front.pid === process.pid) {
			return 'own-window'
		}
		if (source.kind !== 'window') {
			return 'ok'
		}
		const shared = this.windowInfo(source.windowId!)
		if (!shared) {
			return 'focus-elsewhere'
		}
		return front.id === shared.id || (front.pid === shared.pid && containsRect(shared.bounds, front.bounds)) ? 'ok' : 'focus-elsewhere'
	}

	windowState(source: ControlledSource): WindowStateResult {
		if (!source.windowId) {
			return 'normal'
		}
		const info = this.windowInfo(source.windowId)
		if (!info) {
			return 'gone'
		}
		return info.onscreen ? 'normal' : 'hidden'
	}

	bringToFront() {
		// Needs the Accessibility API (AXRaise); left to the pilot to decide on
	}

	foregroundElevated() {
		return false
	}

	async leaveElevated(): Promise<LeaveElevatedResult> {
		return 'not-elevated'
	}

	cursor(): OsPoint | null {
		const native = getBindings()
		if (!native) {
			return null
		}
		const event = native.CGEventCreate(null)
		if (!event) {
			return null
		}
		const point = native.CGEventGetLocation(event)
		native.CFRelease(event)
		return { x: point.x, y: point.y }
	}

	modifiers(): ModifierState | null {
		const native = getBindings()
		if (!native) {
			return null
		}
		const flags = Number(native.CGEventSourceFlagsState(kCGEventSourceStateHIDSystemState))
		return {
			Control: (flags & FLAG_CONTROL) !== 0,
			Alt: (flags & FLAG_ALTERNATE) !== 0,
			Shift: (flags & FLAG_SHIFT) !== 0,
			Meta: (flags & FLAG_COMMAND) !== 0,
		}
	}

	move(point: OsPoint) {
		const native = getBindings()
		if (!native) {
			return
		}
		// While a button is held, moves are drags of that button, or selection and
		// drag-and-drop do not work
		let type = kCGEventMouseMoved
		let button = 0
		if (this.pressedButtons.has(0)) {
			type = kCGEventLeftMouseDragged
		} else if (this.pressedButtons.has(2)) {
			type = kCGEventRightMouseDragged
			button = 1
		} else if (this.pressedButtons.size > 0) {
			type = kCGEventOtherMouseDragged
			button = toCgButton([...this.pressedButtons][0]!)
		}
		this.lastPoint = point
		this.post(native, native.CGEventCreateMouseEvent(native.source, type, point, button))
	}

	button(button: MouseButton, down: boolean, point: OsPoint, clickCount: number) {
		const native = getBindings()
		if (!native) {
			return
		}
		if (!down && !this.pressedButtons.has(button)) {
			return
		}
		this.move(point)
		const type = button === 0
			? (down ? kCGEventLeftMouseDown : kCGEventLeftMouseUp)
			: button === 2
				? (down ? kCGEventRightMouseDown : kCGEventRightMouseUp)
				: (down ? kCGEventOtherMouseDown : kCGEventOtherMouseUp)
		const event = native.CGEventCreateMouseEvent(native.source, type, point, toCgButton(button))
		// Cocoa recognises a double click only by the click state, on both down and up
		native.CGEventSetIntegerValueField(event, kCGMouseEventClickState, Math.max(clickCount, 1))
		this.post(native, event)
		if (down) {
			this.pressedButtons.add(button)
		} else {
			this.pressedButtons.delete(button)
		}
	}

	wheel(dx: number, dy: number, point: OsPoint) {
		const native = getBindings()
		if (!native) {
			return
		}
		this.move(point)
		// DOM: positive dy scrolls down; CoreGraphics: positive wheel1 scrolls up
		const vertical = Math.round(-dy * WHEEL_PIXELS_PER_UNIT)
		const horizontal = Math.round(-dx * WHEEL_PIXELS_PER_UNIT)
		this.post(native, native.CGEventCreateScrollWheelEvent2(native.source, kCGScrollEventUnitPixel, 2, vertical, horizontal, 0))
	}

	key(key: NativeKey, down: boolean) {
		const native = getBindings()
		if (!native || key.mac === null) {
			return
		}
		if (!down && !this.pressedKeys.has(key.mac)) {
			return
		}
		this.sendKey(native, key.mac, down)
	}

	releaseAll() {
		const native = getBindings()
		if (!native) {
			return
		}
		for (const button of [...this.pressedButtons]) {
			this.button(button, false, this.lastPoint, 1)
		}
		for (const key of [...this.pressedKeys]) {
			this.sendKey(native, key, false)
		}
		this.pressedKeys.clear()
		this.pressedButtons.clear()
	}

	clipboardSequence() {
		// No cheap change counter without Objective-C (NSPasteboard.changeCount); the session
		// compares a hash of the text instead
		return null
	}

	async clipboardIsSensitive() {
		try {
			const found = await Promise.all(SENSITIVE_PASTEBOARD_TYPES.map((type) => clipboard.has(`electron application/osclipboard;format="${type}"`)))
			return found.some(Boolean)
		} catch {
			return true
		}
	}

	private flags() {
		let flags = 0
		for (const key of this.pressedKeys) {
			flags |= MODIFIER_FLAGS[key] ?? 0
		}
		return flags
	}

	private sendKey(native: Bindings, key: number, down: boolean) {
		if (down) {
			this.pressedKeys.add(key)
		} else {
			this.pressedKeys.delete(key)
		}
		this.post(native, native.CGEventCreateKeyboardEvent(native.source, key, down))
	}

	private post(native: Bindings, event: Pointer) {
		if (!event) {
			return
		}
		native.CGEventSetFlags(event, this.flags())
		native.CGEventPost(kCGHIDEventTap, event)
		native.CFRelease(event)
	}

	private windowInfo(windowId: number): WindowInfo | null {
		return this.copyWindowList(kCGWindowListOptionIncludingWindow, windowId).find((window) => window.id === windowId) ?? null
	}

	/** On-screen windows, front to back */
	private onScreenWindows(): WindowInfo[] {
		return this.copyWindowList(kCGWindowListOptionOnScreenOnly | kCGWindowListExcludeDesktopElements, 0)
	}

	private copyWindowList(option: number, windowId: number): WindowInfo[] {
		const native = getBindings()
		if (!native) {
			return []
		}
		const list = native.CGWindowListCopyWindowInfo(option, windowId)
		if (!list) {
			return []
		}
		try {
			const result: WindowInfo[] = []
			const count = native.CFArrayGetCount(list)
			for (let i = 0; i < count; i++) {
				const dict = native.CFArrayGetValueAtIndex(list, i)
				const rect = { origin: { x: 0, y: 0 }, size: { width: 0, height: 0 } }
				const boundsDict = native.CFDictionaryGetValue(dict, native.keys.bounds)
				if (!boundsDict || !native.CGRectMakeWithDictionaryRepresentation(boundsDict, rect)) {
					continue
				}
				const onscreen = native.CFDictionaryGetValue(dict, native.keys.onscreen)
				const alpha = this.getNumber(native, dict, native.keys.alpha, true)
				result.push({
					id: this.getNumber(native, dict, native.keys.number) ?? 0,
					pid: this.getNumber(native, dict, native.keys.pid) ?? 0,
					layer: this.getNumber(native, dict, native.keys.layer) ?? 0,
					bounds: { x: rect.origin.x, y: rect.origin.y, width: rect.size.width, height: rect.size.height },
					onscreen: !!onscreen && native.CFBooleanGetValue(onscreen),
					alpha: alpha ?? 1,
				})
			}
			return result
		} finally {
			native.CFRelease(list)
		}
	}

	private getNumber(native: Bindings, dict: Pointer, key: Pointer, float = false): number | null {
		const value = native.CFDictionaryGetValue(dict, key)
		if (!value) {
			return null
		}
		if (float) {
			const out = new Float64Array(1)
			return native.CFNumberGetValue(value, kCFNumberFloat64Type, out) ? out[0]! : null
		}
		const out = new BigInt64Array(1)
		return native.CFNumberGetValue(value, kCFNumberSInt64Type, out) ? Number(out[0]) : null
	}
}

/**
 * Protocol button → CGMouseButton (DOM right is 2, CG right is 1)
 *
 * @param button - Protocol button
 */
function toCgButton(button: MouseButton) {
	return [0, 2, 1, 3, 4][button]!
}

/**
 * @param rect - Rectangle
 * @param point - Point
 */
function contains(rect: OsRect, point: OsPoint) {
	return point.x >= rect.x && point.y >= rect.y && point.x < rect.x + rect.width && point.y < rect.y + rect.height
}

/**
 * @param outer - Outer rectangle
 * @param inner - Inner rectangle
 */
function containsRect(outer: OsRect, inner: OsRect) {
	return inner.x >= outer.x && inner.y >= outer.y && inner.x + inner.width <= outer.x + outer.width && inner.y + inner.height <= outer.y + outer.height
}
